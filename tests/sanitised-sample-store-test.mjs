import assert from 'node:assert/strict';
import test from 'node:test';

import {
  buildSanitisedSampleDoc,
  downloadSanitisedSamplePayload,
  parseSanitisedSampleDoc,
  sanitisedSampleKey,
} from '../src/sanitised-sample-store.ts';

const verification = {
  verdict: 'pass',
  method: 'parser-emulation',
  eventsChecked: 2,
  eventsParsed: 2,
  fields: ['srcip', 'user'],
  reasons: [],
};

test('builds a versioned sanitised sample without the original or alias map', () => {
  const doc = buildSanitisedSampleDoc({
    sourcetype: 'Fortinet_FortiGate',
    format: 'kv',
    events: [
      'srcip=10.8.31.4 user=EXAMPLE\\\\iris.hayes',
      'srcip=10.8.31.9 user=EXAMPLE\\\\ben.stone',
    ],
    verification,
    provenance: {
      sourceMode: 'group',
      sourceLabel: 'fortigate.log',
      replacementsApplied: 4,
      structurePreserved: true,
      coverage: { total: 4, replaced: 4, ok: true, blind: false },
      sanitisedAt: '2026-08-24T14:00:00.000Z',
      buildNumber: 566,
    },
  });

  assert.equal(doc.version, 1);
  assert.equal(doc.key, 'fortinet_fortigate::kv');
  assert.equal(doc.sanitised, true);
  assert.equal(doc.events.length, 2);
  assert.equal(doc.verification.verdict, 'pass');

  const serialised = JSON.stringify(doc);
  assert.doesNotMatch(serialised, /10\.44\.19\.7|m\.devries|original|alias|mapping/i);
});

test('parses only valid sanitised documents', () => {
  const doc = buildSanitisedSampleDoc({
    sourcetype: 'cisco_asa',
    events: ['src=192.0.2.10 dst=198.51.100.20'],
    verification,
    provenance: {
      sourceMode: 'paste',
      sourceLabel: 'pasted events',
      replacementsApplied: 2,
      structurePreserved: true,
      coverage: { total: 2, replaced: 2, ok: true, blind: false },
      sanitisedAt: '2026-08-24T14:00:00.000Z',
    },
  });

  assert.deepEqual(parseSanitisedSampleDoc(JSON.stringify(doc)), doc);
  assert.equal(parseSanitisedSampleDoc({ ...doc, sanitised: false }), null);
  assert.equal(parseSanitisedSampleDoc({ ...doc, events: [] }), null);
  assert.equal(parseSanitisedSampleDoc({ ...doc, key: '../escape' }), null);
});

test('creates safe stable keys', () => {
  assert.equal(sanitisedSampleKey(' Windows Security ', 'XML'), 'windows_security::xml');
  assert.throws(() => sanitisedSampleKey('../secrets'), /sourcetype/i);
});

test('downloads raw lines or evidence JSON without a replacement map', () => {
  const doc = buildSanitisedSampleDoc({
    sourcetype: 'cisco_asa',
    events: ['one=1', 'two=2'],
    verification,
    provenance: {
      sourceMode: 'upload',
      sourceLabel: 'asa.log',
      replacementsApplied: 2,
      structurePreserved: true,
      coverage: { total: 2, replaced: 2, ok: true, blind: false },
      sanitisedAt: '2026-08-24T14:00:00.000Z',
    },
  });

  const log = downloadSanitisedSamplePayload(doc, 'log');
  assert.equal(log.mime, 'text/plain');
  assert.equal(log.body, 'one=1\ntwo=2\n');

  const json = downloadSanitisedSamplePayload(doc, 'json');
  const parsed = JSON.parse(json.body);
  assert.deepEqual(parsed.events, ['one=1', 'two=2']);
  assert.equal(parsed.replacementMap, undefined);
  assert.doesNotMatch(json.body, /original|alias/i);
});

test('the evidence report is self-contained printable HTML with no original data', () => {
  const doc = buildSanitisedSampleDoc({
    sourcetype: 'cisco_asa',
    format: 'kv',
    events: ['src=192.0.2.10 note=<script>alert(1)</script>'],
    verification,
    provenance: {
      sourceMode: 'upload',
      sourceLabel: 'asa.log',
      replacementsApplied: 2,
      structurePreserved: true,
      coverage: { total: 2, replaced: 2, ok: true, blind: false },
      sanitisedAt: '2026-08-24T14:00:00.000Z',
      buildNumber: 618,
    },
  });

  const report = downloadSanitisedSamplePayload(doc, 'report');
  assert.equal(report.mime, 'text/html');
  assert.match(report.filename, /cisco_asa__kv-report\.html$/);
  const html = report.body;
  // A standalone document that can be printed to PDF from the browser.
  assert.match(html, /^<!doctype html>/i);
  assert.match(html, /window\.print\(\)/);
  // Carries the evidence facts…
  assert.match(html, /cisco_asa/);
  assert.match(html, /Identities replaced/);
  assert.match(html, /2\/2 located values replaced/);
  assert.match(html, /parser-emulation/);
  assert.match(html, /build 618|Generated by build/);
  // …and event content is HTML-escaped, never executable, and never leaks originals.
  assert.doesNotMatch(html, /<script>alert/);
  assert.match(html, /&lt;script&gt;/);
  // No serialised mapping structure rides into the report (the privacy note may mention the
  // map by name — that is reassurance copy, not data).
  assert.doesNotMatch(html, /replacementMap|aliasMap|"mapping"/i);
});

test('allowlists provenance so identity details cannot ride into persistence', () => {
  const doc = buildSanitisedSampleDoc({
    sourcetype: 'cisco_asa',
    events: ['src=192.0.2.10'],
    verification,
    provenance: {
      sourceMode: 'paste',
      sourceLabel: 'pasted events',
      replacementsApplied: 1,
      structurePreserved: true,
      coverage: {
        total: 1, replaced: 1, ok: true, blind: false,
        remaining: [{ field: 'user', value: 'customer-name' }],
      },
      sanitisedAt: '2026-08-24T14:00:00.000Z',
      original: 'customer-name',
      alias: 'user-01',
      replacementMap: { 'customer-name': 'user-01' },
    },
  });
  assert.doesNotMatch(JSON.stringify(doc), /customer-name|user-01|replacementMap|remaining/);
});
